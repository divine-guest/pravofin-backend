from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

app = FastAPI()

# Разрешаем запросы с любых источников (это важно для сайта)
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

# Модель для запроса на генерацию документа
class DocRequest(BaseModel):
    docType: str
    party1: str
    party2: str
    amount: str
    term: str

@app.get("/")
def root():
    return {"message": "ПравоФин API работает. Версия без авторизации."}

@app.post("/generate")
async def generate_document(req: DocRequest):
    # Возвращаем сгенерированный документ в виде простого текста
    return {
        "document": f"""
ДОГОВОР КУПЛИ-ПРОДАЖИ

г. Москва                     "___"__________ 2026 г.

{req.party1}, именуемое в дальнейшем «Продавец», и {req.party2}, именуемое в дальнейшем «Покупатель», заключили настоящий договор о следующем:

1. ПРЕДМЕТ ДОГОВОРА
Продавец обязуется передать в собственность Покупателя товар на сумму {req.amount} ₽, а Покупатель обязуется принять товар и оплатить его.

2. ЦЕНА И ПОРЯДОК РАСЧЁТОВ
Общая стоимость товара составляет {req.amount} ₽.
Покупатель оплачивает товар в течение {req.term} дней с момента подписания договора.

3. СРОКИ И УСЛОВИЯ ПОСТАВКИ
Продавец обязуется поставить товар в течение {req.term} дней с момента получения предоплаты.

4. ОТВЕТСТВЕННОСТЬ СТОРОН
За неисполнение или ненадлежащее исполнение обязательств по настоящему договору Стороны несут ответственность в соответствии с действующим законодательством РФ.

5. РЕКВИЗИТЫ И ПОДПИСИ
Продавец: {req.party1}
Покупатель: {req.party2}

Подписи сторон:
___________________
___________________
"""
    }
